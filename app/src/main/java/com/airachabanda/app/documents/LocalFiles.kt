package com.airachabanda.app.documents

import java.io.File

object TemporaryFiles {
    fun sweep(cache: File, nowEpochMs: Long, maxAgeMs: Long = 60 * 60 * 1000L): Int {
        if (!cache.isDirectory) return 0
        var removed = 0
        cache.walkTopDown().filter { it.isFile && nowEpochMs - it.lastModified() > maxAgeMs }.forEach { file ->
            if (file.delete()) removed += 1
        }
        return removed
    }
}

object LocalStorageReport {
    fun describe(files: File, cache: File): String {
        fun size(directory: File): Long =
            if (directory.isDirectory) directory.walkTopDown().filter { it.isFile }.sumOf { it.length() } else 0L
        val attachments = size(File(files, "attachments"))
        val generated = size(File(files, "generated"))
        val credentials = size(File(files, "credentials"))
        val cached = size(cache)
        return "Imported attachments $attachments bytes. Generated documents $generated bytes. " +
            "Encrypted credential files $credentials bytes. Cache $cached bytes. " +
            "Conversation text in the database is not included in these file sizes and is not encrypted. " +
            "Deleting a conversation removes its imported files and generated files. " +
            "Completed conversations are kept until you delete them. Abandoned cache files older than one hour are removed at startup."
    }
}
