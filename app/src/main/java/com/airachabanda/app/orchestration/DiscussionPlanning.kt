package com.airachabanda.app.orchestration

import com.airachabanda.app.core.model.ResearchMode

/**
 * Deterministic discussion planning. This object does not call a model.
 * A future model-generated plan would be a separate source and is not used here.
 */
object DiscussionPlanner {
    const val SOURCE = "DETERMINISTIC"

    private val numberedPart = Regex("""^\d+[\.\)]\s+(\S.*)""")
    private val arithmetic = Regex("""\d+\s*[+\-*/×÷]\s*\d+""")

    data class Signals(
        val objective: String,
        val mode: ResearchMode,
        val explicitCapabilities: Set<String>,
        val participantCount: Int,
        val requestBudget: Int,
        val deadlineEpochMs: Long?,
        val nowEpochMs: Long,
        val consequences: Boolean,
    )

    data class Work(
        val localId: String,
        val objective: String,
        val parentLocalId: String?,
        val dependsOn: Set<String>,
        val capability: String,
        val expectedOutput: String,
        val priority: Int,
        val budget: Int,
        val kind: String,
    )

    data class Plan(
        val source: String,
        val decompose: Boolean,
        val verificationRequired: Boolean,
        val critiqueRequired: Boolean,
        val concurrencyLimit: Int,
        val delegationDepthLimit: Int,
        val fanOutLimit: Int,
        val addedCapabilities: Set<String>,
        val tasks: List<Work>,
        val note: String,
    )

    fun needsArithmeticCheck(objective: String): Boolean = arithmetic.containsMatchIn(objective)

    fun parts(objective: String): List<String> {
        val numbered = objective.lines().map { it.trim() }.mapNotNull { line ->
            numberedPart.find(line)?.groupValues?.get(1)?.trim()
        }
        return if (numbered.size >= 2) numbered else emptyList()
    }

    fun plan(signals: Signals): Plan {
        val segments = parts(signals.objective)
        val arithmeticNeeded = needsArithmeticCheck(signals.objective)
        val timeBoxed = signals.deadlineEpochMs != null && signals.deadlineEpochMs <= signals.nowEpochMs
        val consequences = signals.consequences || signals.mode == ResearchMode.DEEP_RESEARCH
        val verificationRequired = arithmeticNeeded || RoleAssignment.VERIFICATION in signals.explicitCapabilities
        val critique = when (signals.mode) {
            ResearchMode.QUICK -> RoleAssignment.CRITIQUE in signals.explicitCapabilities
            ResearchMode.CUSTOM -> RoleAssignment.CRITIQUE in signals.explicitCapabilities
            ResearchMode.STANDARD, ResearchMode.DEEP_RESEARCH -> true
        }
        val decompose = segments.size >= 2 && signals.mode != ResearchMode.QUICK
        val participants = signals.participantCount.coerceAtLeast(1)
        val concurrency = when (signals.mode) {
            ResearchMode.QUICK -> 1
            ResearchMode.STANDARD, ResearchMode.CUSTOM -> minOf(2, participants)
            ResearchMode.DEEP_RESEARCH -> minOf(3, participants)
        }
        val depth = when (signals.mode) {
            ResearchMode.QUICK -> 1
            ResearchMode.STANDARD, ResearchMode.CUSTOM -> 2
            ResearchMode.DEEP_RESEARCH -> 3
        }
        val added = mutableSetOf<String>()
        if (signals.mode == ResearchMode.STANDARD || signals.mode == ResearchMode.DEEP_RESEARCH) {
            added += RoleAssignment.CRITIQUE
        }
        if (signals.mode == ResearchMode.DEEP_RESEARCH || verificationRequired) {
            added += RoleAssignment.VERIFICATION
        }
        val tasks = if (decompose) {
            val children = segments.mapIndexed { index, part ->
                Work(
                    localId = "part-$index",
                    objective = part,
                    parentLocalId = "analysis",
                    dependsOn = emptySet(),
                    capability = RoleAssignment.RESEARCH,
                    expectedOutput = "A sourced finding for this part, or a statement that no source was supplied.",
                    priority = 2,
                    budget = 1,
                    kind = "RESEARCH",
                )
            }
            children + Work(
                localId = "analysis",
                objective = "Combine the completed parts. Do not treat a missing part as established.",
                parentLocalId = null,
                dependsOn = children.map { it.localId }.toSet(),
                capability = RoleAssignment.ANALYSIS,
                expectedOutput = "Findings that cite the completed parts and name any missing part.",
                priority = 1,
                budget = 1,
                kind = "ANALYSIS",
            )
        } else {
            emptyList()
        }
        val note = buildString {
            append("Deterministic plan. This plan was not generated by a model. ")
            append("Mode ${signals.mode.name}. Participants ${signals.participantCount}. ")
            append("Request budget ${signals.requestBudget}. ")
            append(if (segments.size >= 2) "${segments.size} numbered parts. " else "One request, without a numbered split. ")
            append(if (arithmeticNeeded) "A numeric expression needs verification. " else "No numeric expression was found. ")
            append(if (consequences) "An incorrect conclusion matters for this mode. " else "No extra consequence flag was set. ")
            append(if (timeBoxed) "The deadline has already passed. " else "")
            append(if (decompose) "Independent parts can run together. " else "No extra split was planned. ")
            append("Critical review is ${if (critique) "included" else "not opened"}.")
        }
        return Plan(
            source = SOURCE,
            decompose = decompose,
            verificationRequired = verificationRequired,
            critiqueRequired = critique,
            concurrencyLimit = concurrency,
            delegationDepthLimit = depth,
            fanOutLimit = depth,
            addedCapabilities = added,
            tasks = tasks,
            note = note.trim(),
        )
    }
}

object TaskGraph {
    data class Node(
        val id: String,
        val state: String,
        val automated: Boolean,
        val dependsOn: Set<String>,
        val deadlineEpochMs: Long?,
        val priority: Int,
    )

    data class Promotion(
        val activateAutomated: List<String>,
        val activateAssisted: List<String>,
        val cancel: List<String>,
    )

    private val success = setOf("COMPLETED", "SKIPPED")
    private val failure = setOf("CANCELLED", "FAILED", "BLOCKED")
    private val active = setOf("PENDING", "READY", "RUNNING", "AWAITING_USER_RESPONSE", "DEFERRED")

    fun hasCycle(edges: List<Pair<String, String>>): Boolean {
        val adjacent = edges.groupBy({ it.first }, { it.second })
        val visiting = mutableSetOf<String>()
        val visited = mutableSetOf<String>()
        fun walk(id: String): Boolean {
            if (id in visiting) return true
            if (id in visited) return false
            visiting += id
            if (adjacent[id].orEmpty().any { walk(it) }) return true
            visiting -= id
            visited += id
            return false
        }
        return adjacent.keys.any { walk(it) }
    }

    fun promote(nodes: List<Node>, concurrencyLimit: Int, nowEpochMs: Long): Promotion {
        val limit = concurrencyLimit.coerceAtLeast(1)
        val cancel = mutableSetOf<String>()
        var changed = true
        while (changed) {
            changed = false
            nodes.forEach { node ->
                if (node.id in cancel || node.state in success || node.state in failure) return@forEach
                val timedOut = node.deadlineEpochMs != null && node.deadlineEpochMs <= nowEpochMs && node.state !in failure
                val failedDependency = node.dependsOn.any { dependency ->
                    val upstream = nodes.firstOrNull { it.id == dependency }
                    dependency in cancel || upstream?.state in failure
                }
                if ((timedOut || failedDependency) && cancel.add(node.id)) changed = true
            }
        }
        fun ready(node: Node): Boolean {
            if (node.state != "QUEUED" || node.id in cancel) return false
            return node.dependsOn.all { dependency ->
                nodes.firstOrNull { it.id == dependency }?.state in success
            }
        }
        val ready = nodes.filter { ready(it) }.sortedByDescending { it.priority }
        val automatedRoom = (limit - nodes.count { it.automated && it.state in active && it.id !in cancel }).coerceAtLeast(0)
        val assistedRoom = (limit - nodes.count { !it.automated && it.state in active && it.id !in cancel }).coerceAtLeast(0)
        return Promotion(
            activateAutomated = ready.filter { it.automated }.take(automatedRoom).map { it.id },
            activateAssisted = ready.filter { !it.automated }.take(assistedRoom).map { it.id },
            cancel = cancel.toList(),
        )
    }
}

object BudgetLedger {
    fun reserve(remaining: Int, requested: Int, reviewReserve: Int): Boolean {
        if (requested < 0) return false
        if (requested == 0) return true
        return remaining - requested >= reviewReserve.coerceAtLeast(0)
    }

    fun bounded(current: Int, proposed: Int): Int = if (proposed > current) current else proposed.coerceAtLeast(0)
}

enum class ExecutionIntent {
    PREPARE_ASSISTED_TASK,
    RECORD_IMPORTED_TEXT,
    ENABLE_BILLING,
    READ_CREDENTIAL,
    OPEN_NETWORK,
    EXECUTE_CODE,
    RAISE_BUDGET,
    GRANT_PERMISSION,
}

object ExecutionGate {
    fun allow(intent: ExecutionIntent): Boolean = when (intent) {
        ExecutionIntent.PREPARE_ASSISTED_TASK,
        ExecutionIntent.RECORD_IMPORTED_TEXT,
        -> true
        ExecutionIntent.ENABLE_BILLING,
        ExecutionIntent.READ_CREDENTIAL,
        ExecutionIntent.OPEN_NETWORK,
        ExecutionIntent.EXECUTE_CODE,
        ExecutionIntent.RAISE_BUDGET,
        ExecutionIntent.GRANT_PERMISSION,
        -> false
    }

    fun retryUnknownOutcome(): Boolean = false
}

object TaskContext {
    const val LIMIT = 1_200

    fun initial(objective: String, userContext: List<String>): String =
        IndependentBrief.research(objective, userContext)

    fun targeted(
        objective: String,
        claims: List<String>,
        objections: List<String>,
        evidence: List<String>,
    ): String {
        val body = buildString {
            appendLine("Assigned task. Other participants' initial answers are not included.")
            appendLine("Objective:")
            appendLine(objective.trim())
            appendLine("Recorded claims:")
            appendList(claims, "No claim was shared.")
            appendLine("Objections:")
            appendList(objections, "No objection was shared.")
            appendLine("Source references:")
            appendList(evidence, "No source was recorded.")
        }
        if (body.length <= LIMIT) return body.trim()
        return buildString {
            appendLine("Context summary. This summary is not the original source.")
            appendLine("Objective:")
            appendLine(objective.trim().take(400))
            appendLine("Source references:")
            if (evidence.isEmpty()) {
                appendLine("No source was recorded.")
            } else {
                evidence.forEach { appendLine("- $it") }
            }
        }.trim()
    }

    private fun StringBuilder.appendList(items: List<String>, empty: String) {
        if (items.isEmpty()) appendLine(empty) else items.forEach { appendLine("- $it") }
    }
}

object DiscussionQuality {
    data class Check(
        val requirementsAddressed: Boolean,
        val claimsMissingEvidence: Boolean,
        val materialDisagreement: Boolean,
        val mathVerificationRequired: Boolean,
        val mathVerificationDone: Boolean,
        val critiqueCompletedOrUnavailable: Boolean,
        val furtherResearchWouldHelp: Boolean,
        val budgetRemaining: Int,
    )

    data class Decision(val readyForSynthesis: Boolean, val note: String)

    fun assess(check: Check): Decision {
        val mathClear = !check.mathVerificationRequired || check.mathVerificationDone
        val ready = check.critiqueCompletedOrUnavailable && mathClear && !check.furtherResearchWouldHelp
        val note = buildString {
            append(if (check.requirementsAddressed) "The recorded requirements are addressed. " else "A requirement is still open. ")
            append(if (check.claimsMissingEvidence) "A claim has no stored source. " else "Stored sources are listed with the claims that have them. ")
            append(if (check.materialDisagreement) "A material disagreement remains. " else "No material disagreement is recorded. ")
            append(if (mathClear) "Mathematical verification is not outstanding. " else "Mathematical verification is still required. ")
            append(if (check.critiqueCompletedOrUnavailable) "Critical review is complete or unavailable. " else "Critical review is still open. ")
            append(if (check.furtherResearchWouldHelp) "Another research task could still change the answer. " else "Further research is not expected to change the answer. ")
            append("Remaining automated budget ${check.budgetRemaining} is not a reason to continue. This is not a confidence score.")
        }
        return Decision(ready, note.trim())
    }
}

object SynthesisBrief {
    data class Input(
        val objective: String,
        val corrections: List<String>,
        val findings: List<String>,
        val evidence: List<String>,
        val contradictions: List<String>,
        val unresolved: List<String>,
        val verificationLimits: String,
        val participants: List<String>,
        val verifiedCalculations: List<String> = emptyList(),
        val assumptions: List<String> = emptyList(),
        val alternatives: List<String> = emptyList(),
    )

    fun prepare(input: Input): String = buildString {
        appendLine("Synthesis input for an eligible participant. This text is not the final answer.")
        appendLine("Direct answer requirements:")
        appendLine(input.objective.trim().ifBlank { "No objective was stored." })
        appendLine("Supported findings:")
        appendItems(input.findings, "No finding was stored.")
        appendLine("Verified calculations:")
        appendItems(input.verifiedCalculations, "No calculation was verified.")
        appendLine("Evidence references:")
        appendItems(input.evidence, "No source was recorded.")
        appendLine("Confirmed corrections:")
        appendItems(input.corrections, "No correction was stored.")
        appendLine("Material assumptions:")
        appendItems(input.assumptions, "No assumption was recorded.")
        appendLine("Alternative interpretations:")
        appendItems(input.alternatives, "No alternative was recorded.")
        appendLine("Contradictions:")
        appendItems(input.contradictions, "No contradiction was stored.")
        appendLine("Unresolved objections:")
        appendItems(input.unresolved, "No unresolved objection was stored.")
        appendLine("Verification limitations: ${input.verificationLimits.ifBlank { "Not recorded." }}")
        appendLine("Participants and model identities:")
        appendItems(input.participants, "No participant is assigned.")
        append("Do not invent citations, evidence, or a confidence percentage.")
    }.trim()

    private fun StringBuilder.appendItems(items: List<String>, empty: String) {
        if (items.isEmpty()) appendLine(empty) else items.forEach { appendLine("- $it") }
    }
}
